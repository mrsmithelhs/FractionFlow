import { afterEach, describe, expect, it } from 'vitest';
import { PRACTICE_TYPES, PLAN39_BAR_TO_LINE_PRACTICE_TYPE } from '../src/app/practice-types.js';
import { createFractionFlowApp } from '../src/app/app.js';
import { setupMockDOM, teardownMockDOM } from './fixtures/mock-dom.js';

describe('Plan 39 app wiring', () => {
  afterEach(() => teardownMockDOM());

  it('registers eight records and starts a unary encounter without binary fixture operands', () => {
    expect(PRACTICE_TYPES).toContain(PLAN39_BAR_TO_LINE_PRACTICE_TYPE);
    expect(PLAN39_BAR_TO_LINE_PRACTICE_TYPE.items).toHaveLength(8);
    const document = setupMockDOM();
    const root = document.createElement('div');
    document.body.appendChild(root);
    const app = createFractionFlowApp({ root, presentationMode: 'instant-test' }).mount();
    root.querySelector('[data-practice-type="bar-to-line-same-amount"]').click();
    expect(app.getState().episodeDefinition.id).toBe('phase-4-bar-to-line-same-amount');
    expect(app.getState().content).not.toHaveProperty('operands');
    expect(root.querySelectorAll('.plan39-source-figure')).toHaveLength(2);
    expect(root.querySelectorAll('.plan39-track-figure')).toHaveLength(2);
    expect(root.querySelectorAll('.plan39-candidates-visual input[type="radio"]')).toHaveLength(0);
    expect(root.querySelector('.app-replay-button').hidden).toBe(true);
    app.destroy();
  });

  it('keeps an unconfirmed stepper preview across view changes and submits only on Check position', () => {
    const document = setupMockDOM();
    const root = document.createElement('div');
    document.body.appendChild(root);
    const app = createFractionFlowApp({ root, presentationMode: 'instant-test' }).mount();
    root.querySelector('[data-practice-type="bar-to-line-same-amount"]').click();
    root.querySelector('.app-visual-view .plan39-continue').click();
    expect(app.getState().beat).toBe('locate');
    const next = root.querySelector('.app-visual-view .plan39-stepper-next');
    next.click();
    next.click();
    expect(app.getState().beat).toBe('locate');
    expect(app.getState().intentHistory.map((intent) => intent.type)).toEqual(['acknowledge-bridge-encounter']);
    expect(root.querySelector('.app-visual-view .plan39-check-position').disabled).toBe(false);
    root.querySelector('.app-view-toggle').click();
    const linearRadio = root.querySelector('.app-linear-view').querySelectorAll('input').find((input) => input.getAttribute('data-candidate-id') === 'partition-1-of-2');
    expect(linearRadio.checked).toBe(true);
    root.querySelector('.app-view-toggle').click();
    expect(root.querySelector('.app-visual-view .plan39-stepper-status').getAttribute('data-candidate-id')).toBe('partition-1-of-2');
    expect(app.getState().beat).toBe('locate');
    root.querySelector('.app-visual-view .plan39-check-position').click();
    expect(app.getState().beat).toBe('resolve');
    expect(root.querySelector('.app-visual-view .plan39-accepted-point')).not.toBeNull();
    root.querySelector('.app-visual-view .plan39-finish').click();
    expect(app.getState().status).toBe('resolved');
    expect(root.querySelector('.app-visual-view .plan39-finish')).toBeNull();
    expect(root.querySelector('.app-next-button').hasAttribute('hidden')).toBe(false);
    expect(root.querySelector('.app-visual-view .active-beat-prompt').textContent).toBe('The same amount is on the number line.');
    app.destroy();
  });

  it('keeps help and recovery scoped to the active view, then clears both on reset and return', () => {
    const document = setupMockDOM();
    const root = document.createElement('div');
    document.body.appendChild(root);
    const app = createFractionFlowApp({ root, presentationMode: 'instant-test' }).mount();
    root.querySelector('[data-practice-type="bar-to-line-same-amount"]').click();
    root.querySelector('.app-visual-view .plan39-continue').click();
    expect(document.activeElement.classList.contains('plan39-stepper-next')).toBe(true);
    root.querySelector('.app-visual-view .plan39-stepper-next').click();
    root.querySelector('.app-visual-view .plan39-check-position').click();
    expect(app.getState().beat).toBe('locate');
    expect(app.getState().lastRecovery.classification.kind).toBe('at-endpoint');
    expect(root.querySelector('.app-visual-view .plan39-feedback').getAttribute('role')).toBe('alert');
    const help = root.querySelector('.app-support-controls button');
    help.click();
    expect(help.getAttribute('aria-controls')).toBe('visual-plan39-help');
    expect(root.querySelector('#visual-plan39-help').textContent).toMatch(/shaded part/);
    root.querySelector('.app-view-toggle').click();
    expect(help.getAttribute('aria-controls')).toBe('linear-plan39-help');
    expect(root.querySelector('#linear-plan39-help')).not.toBeNull();
    expect(root.querySelector('.app-linear-view .plan39-feedback')).not.toBeNull();
    root.querySelector('.app-view-toggle').click();
    help.click();
    expect(root.querySelector('#visual-plan39-help')).toBeNull();
    help.click();
    expect(root.querySelector('#visual-plan39-help')).not.toBeNull();
    root.querySelector('.app-restart-button').click();
    expect(app.getState().beat).toBe('encounter');
    expect(root.querySelector('#visual-plan39-help')).toBeNull();
    expect(root.querySelector('.app-visual-view .plan39-stepper-status')).toBeNull();
    root.querySelector('.app-visual-view .plan39-continue').click();
    expect(root.querySelector('.app-visual-view .plan39-check-position').disabled).toBe(true);
    root.querySelector('.app-return-button').click();
    expect(root.querySelector('.app-episode').hasAttribute('hidden')).toBe(true);
    root.querySelector('[data-practice-type="bar-to-line-same-amount"]').click();
    root.querySelector('.app-visual-view .plan39-continue').click();
    expect(root.querySelector('.app-visual-view .plan39-check-position').disabled).toBe(true);
    expect(root.querySelector('#visual-plan39-help')).toBeNull();
    app.destroy();
  });
});
